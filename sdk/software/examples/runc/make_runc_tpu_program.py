#!/usr/bin/env python3
"""Generate the TPU instruction stream used by the runc Llama example."""

from __future__ import annotations

import argparse
from pathlib import Path


TPU_TILE = 8
TPU_K_CHUNK = 64
TPU_BANK_STRIDE = 1024
TPU_SCRATCH_BASE = 1800

OP_SET_WR = 0x2
OP_UB_READ = 0x3
OP_SWITCH = 0x4
OP_WAIT = 0x5
OP_END = 0xF

PTR_INPUT = 0
PTR_WEIGHT = 1
WAIT_CYCLES = 0

WEIGHT_READY_WAIT = 32
SWITCH_SETTLE_WAIT = 12
COMPUTE_WAIT = 160
FINAL_DRAIN_WAIT = 512


def word_set_wr(addr: int, accumulate: bool = False) -> int:
    return (
        ((OP_SET_WR & 0xF) << 28)
        | ((addr & 0x0FFF) << 16)
        | ((1 if accumulate else 0) << 15)
    )


def word_ub_read(ptr_select: int, addr: int, rows: int, cols: int, transpose: bool, vpu_mode: int) -> int:
    return (
        ((OP_UB_READ & 0xF) << 28)
        | ((ptr_select & 0x7) << 25)
        | ((addr & 0x0FFF) << 13)
        | ((rows & 0xF) << 9)
        | ((cols & 0xF) << 5)
        | ((1 if transpose else 0) << 4)
        | (vpu_mode & 0xF)
    )


def word_switch() -> int:
    return (OP_SWITCH & 0xF) << 28


def word_wait(cycles: int) -> int:
    return ((OP_WAIT & 0xF) << 28) | ((WAIT_CYCLES & 0xF) << 24) | (cycles & 0x00FFFFFF)


def word_end() -> int:
    return (OP_END & 0xF) << 28


def build_matmul_program(bank: int) -> list[int]:
    x_base = bank * TPU_BANK_STRIDE
    w_base = x_base + TPU_K_CHUNK
    program: list[int] = []
    for kt in range(TPU_K_CHUNK // TPU_TILE):
        program.extend(
            [
                word_ub_read(
                    PTR_WEIGHT,
                    w_base + kt * TPU_TILE * TPU_TILE,
                    TPU_TILE,
                    TPU_TILE,
                    True,
                    0x0,
                ),
                word_wait(WEIGHT_READY_WAIT),
                word_switch(),
                word_wait(SWITCH_SETTLE_WAIT),
                word_set_wr(TPU_SCRATCH_BASE, False),
                word_ub_read(PTR_INPUT, x_base + kt * TPU_TILE, 1, TPU_TILE, False, 0x0),
                word_wait(COMPUTE_WAIT),
            ]
        )
    # OP_END only observes a short quiet window in older bitstreams. Keep the
    # final systolic wave alive long enough for all eight lanes to cross CDC.
    program.append(word_wait(FINAL_DRAIN_WAIT))
    program.append(word_end())
    return program


def write_header(path: Path, programs: list[list[int]]) -> None:
    words = programs[0]
    if any(len(program) != len(words) for program in programs):
        raise ValueError("all bank programs must have equal length")
    lines = [
        "/* Auto-generated by make_runc_tpu_program.py. */",
        "#ifndef RUNC_TPU_PROGRAM_H",
        "#define RUNC_TPU_PROGRAM_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define RUNC_TPU_PROGRAM_WORDS {len(words)}u",
        f"#define RUNC_TPU_PROGRAM_BANKS {len(programs)}u",
    ]
    for bank, program in enumerate(programs):
        lines.append(
            f"static const uint32_t runc_tpu_matmul_program_bank{bank}[] "
            "__attribute__((aligned(64))) = {"
        )
        for word in program:
            lines.append(f"    0x{word:08x}u,")
        lines.append("};")
    lines.extend(
        [
            "",
            "#endif",
            "",
        ]
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, help="output header path")
    args = parser.parse_args()

    programs = [build_matmul_program(bank) for bank in range(2)]
    write_header(Path(args.out), programs)
    print(f"[runc_tpu] wrote {args.out} ({len(programs[0])} words x {len(programs)} banks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
